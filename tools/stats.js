// Collect level-set statistics into docs/LEVEL_STATS.md (one section per set).
import fs from 'node:fs';
const FILE = new URL('../docs/LEVEL_STATS.md', import.meta.url);

export function writeStats(name, levels, binned, ms) {
  let doc = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '# Level stats\n\nGenerated by tools/build-levels.js and tools/build-daily.js. Re-run to refresh.\n';
  const pars = levels.map((l) => l.p);
  const first30 = levels.slice(0, 30).map((l) => l.p);
  const shapes = {};
  levels.forEach((l) => { const k = `${l.shape}`; shapes[k] = (shapes[k] || 0) + 1; });
  const myst = levels.filter((l) => l.m).length;
  const opt = levels.filter((l) => l.opt).length;
  const nuts = levels.map((l) => l.c * l.h);
  const bytes = Buffer.byteLength(JSON.stringify({ levels }));
  const section = [
    `<!-- ${name} -->`,
    `## ${name}`,
    '',
    `- boards shipped: **${levels.length}** (file ~${(bytes / 1024).toFixed(1)} KB)`,
    `- par range: ${Math.min(...pars)}–${Math.max(...pars)} (first 30: ${first30.join(', ')})`,
    `- nuts: ${Math.min(...nuts)}–${Math.max(...nuts)}; colours ${Math.min(...levels.map((l) => l.c))}–${Math.max(...levels.map((l) => l.c))}; heights ${Math.min(...levels.map((l) => l.h))}–${Math.max(...levels.map((l) => l.h))}`,
    `- shapes: ${Object.entries(shapes).map(([k, v]) => `${k} ${v}`).join(', ')}; mystery boards: ${myst}`,
    `- par proven optimal: ${opt}/${levels.length} (rest = best found by anytime weighted A*)`,
    `- binned while building: ${binned.unsolvable} unsolvable, ${binned.boring} boring, ${binned.outOfBand} outside par window`,
    `- build time: ${(ms / 1000).toFixed(1)}s`,
    `<!-- /${name} -->`,
  ].join('\n');
  const re = new RegExp(`<!-- ${name} -->[\\s\\S]*?<!-- /${name} -->`);
  doc = re.test(doc) ? doc.replace(re, section) : doc.trimEnd() + '\n\n' + section + '\n';
  fs.writeFileSync(FILE, doc);
}
